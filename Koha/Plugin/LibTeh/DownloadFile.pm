sub uploader_manager {
    my ($self) = @_;
    my $cgi = CGI->new;
    # File manager exposes all uploaded files: require staff cataloguing rights.
    my $session_user = $self->_current_user();
    my $patron = $session_user ? Koha::Patrons->find($session_user->{borrowernumber}) : undef;
    unless ( $patron && $patron->has_permission({ editcatalogue => 'edit_catalogue' }) ) {
        return $self->output_html('<h1>403 Forbidden</h1>', '403 Forbidden');
    }
    my $term = $cgi->param('search') // '';
    $term = substr($term, 0, 150);
    my $page = $cgi->param('page') // 1;
    $page = 1 unless $page =~ /^[1-9]\d{0,5}$/;
    my $per_page = 50;

    # Filter in the database BEFORE pagination. LIKE uses the database's
    # Unicode collation; never filter just the current page in Perl.
    my $where = {};
    if (length $term) {
        my $escaped = $term;
        $escaped =~ s/([%_\\])/\\$1/g;
        $where->{filename} = { -like => "%$escaped%" };
    }
    my $rows = Koha::UploadedFiles->search(
        $where,
        { order_by => { -desc => 'id' }, rows => $per_page, page => $page }
    );
    my @files;
    while (my $file = $rows->next) {
        push @files, {
            filename  => $file->filename // '',
            hashvalue => $file->hashvalue,
            dir       => $file->dir // '',
        };
    }
    my $total = Koha::UploadedFiles->search($where)->count;
    my $opac_url = C4::Context->preference('OPACBaseURL') // '';
    $opac_url =~ s{/+$}{};
    # Do not construct a malformed or script-scheme OPAC download link.
    $opac_url = '' unless $opac_url =~ m{\Ahttps?://[^\s/]+(?::\d+)?(?:/[^\s]*)?\z}i;
    my $rights = $self->retrieve_data('default_rights') // 'authorized_user';
    $rights = 'authorized_user' unless $rights =~ /\A(?:authorized_user|open_acces|staff|admin|local)\z/;
    my $index = $cgi->param('index') // '';
    $index = '' unless $index =~ /^[A-Za-z0-9_-]{1,150}$/;
    my $biblionumber = $cgi->param('biblionumber') // '';
    $biblionumber = '' unless $biblionumber =~ /^\d+$/;
    my $template = $self->get_template({ file => 'templates/uploader-manager.tt' });
    $template->param(
        files => \@files,
        search => $term,
        page => $page,
        total => $total,
        next_page => $page * $per_page < $total ? $page + 1 : 0,
        previous_page => $page > 1 ? $page - 1 : 0,
        biblionumber => $biblionumber,
        index => $index,
        selected_rights => $rights,
        opac_url => $opac_url,
    );
    return $self->output_html($template->output);
}

sub configure {
    my ( $self, $args ) = @_;

    $self->_ensure_authorised_values;

    my $input = CGI->new;
    my $template = $self->get_template({ file => 'templates/configure.tt' });

    if ( ( $input->param('op') // '' ) eq 'cud-save' ) {
        my @rights = qw(admin authorized_user local open_acces staff);
        my $default_rights = $input->param('default_rights') // 'authorized_user';
        $default_rights = 'authorized_user' unless grep { $_ eq $default_rights } @rights;
        $self->store_data({ default_rights => $default_rights });

        for my $right (@rights) {
            my $message = $input->param("denial_$right") // '';
            $self->store_data({
                "denial_$right" => $message
            });
        }


        

        $self->store_data({
            local_networks => scalar( $input->param('local_networks') // '' ),
        });

        my $extensions = lc( $input->param('allowed_extensions') // '' );
        my @extensions = grep { length } map { s/^\s+|\s+$//gr } split /[,\s;]+/, $extensions;
        if ( @extensions && !grep { $_ !~ /^[a-z0-9]{1,12}$/ } @extensions ) {
            my %seen;
            $self->store_data({ allowed_extensions => join(',', grep { !$seen{$_}++ } @extensions) });
        } else {
            $template->param(extensions_error => 1);
        }
        $template->param(saved => 1) unless $template->param('extensions_error');
    }

    my %denial_messages;
    for my $right (qw(admin authorized_user local open_acces staff)) {
        $denial_messages{$right} = $self->retrieve_data("denial_$right") // '';
    }

    $template->param(
        PLUGIN_CLASS => $self->{class},
        denial_messages => \%denial_messages,
        default_rights => ($self->retrieve_data('default_rights') // 'authorized_user'),
        local_networks  => $self->retrieve_data('local_networks') // '',
        allowed_extensions => $self->retrieve_data('allowed_extensions') // 'pdf,djvu,doc,docx,txt,rtf,html',
    );

    return $self->output_html(
        $template->output
    );
}

